// Fact sheets of the phone models the shop sells: the "Fiche de l'appareil"
// on every phone page and the specs of the promo pages (/offres/<model>).
// Manufacturers' published specifications (Apple, Samsung, Xiaomi, Honor,
// cross-checked with GSMArena), written once in a neutral technical form
// (numbers, units, product names) that reads the same in every language.
// What needs words (how it unlocks, the speakers, battery life) is a code
// translated in lib/offers/copy.
//
// Keyed by the model's slug (offerSlug(modelKey) in phone-offers.ts: the
// ERP's "apple|iphone 14 pro" → "iphone-14-pro"). A model missing here just
// shows no spec sheet. Facts that vary by country version (SIM tray,
// Samsung's chip) are only stated when they are known for the shop's units.
// RAM and storage come from each listing (ERP), not from here.

export type Unlock = "faceid" | "ultrasonic" | "optical" | "side" | "face";

export type ModelFacts = {
  /** shown as the page title, e.g. "iPhone 14 Pro" */
  name: string;
  /** iPhones measure their own battery health (Settings > Battery) */
  batteryHealth: boolean;
  /** charging port, for the add-ons (cables, chargers) */
  port: "lightning" | "usb-c";
  /** Apple doesn't publish it; the figure every teardown agrees on */
  ram?: string;
  /** how it unlocks, when the maker states it */
  unlock?: Unlock;
  /** stereo speakers (false = not stated) */
  stereo: boolean;
  /** hours of video playback when new (manufacturer's figure), if published */
  videoHours?: number;
  // Highlights (the promo page's "why" cards): short titles.
  chip: string;
  displayTitle: string;
  cameraTitle: string;
  durabilityTitle?: string;
  extra?: string;
  // The specifications.
  specs: {
    display: string;
    chip: string;
    rearCameras: string;
    frontCamera: string;
    battery: string;
    charging: string;
    durability?: string;
    network?: string;
    sim?: string;
    size?: string;
  };
};

